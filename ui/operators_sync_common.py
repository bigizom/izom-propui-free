def _izom_propui_free_syncable_prop_type(prop_type):
    return izom_propui_free_is_managed_prop_type(prop_type)


def _izom_propui_free_apply_entry_snapshot(entry):
    data = {
        field_name: getattr(entry, field_name, None)
        for field_name in _IZOM_PROPUI_FREE_SYNC_ENTRY_FIELDS
    }
    data['uid'] = str(getattr(entry, 'uid', '') or '').strip()
    data['prop_type'] = str(data.get('prop_type', 'FLOAT') or 'FLOAT').strip().upper() or 'FLOAT'
    return data


def _izom_propui_free_apply_entry_snapshots(params):
    return [
        _izom_propui_free_apply_entry_snapshot(entry)
        for entry in getattr(params, 'izom_propui_free_entries', []) or []
    ]


def _izom_propui_free_replace_storage_for_apply(params, replace_storage_mode='APPLY_SETTING'):
    normalized_mode = str(replace_storage_mode or 'APPLY_SETTING').strip().upper() or 'APPLY_SETTING'
    if normalized_mode == 'REPLACE':
        return True
    if normalized_mode == 'PRESERVE':
        return False
    return bool(getattr(params, 'izom_propui_free_replace_storage_on_apply', False))


def _izom_propui_free_clean_old_targets_for_apply(params, clean_old_targets_mode='APPLY_SETTING'):
    normalized_mode = str(clean_old_targets_mode or 'APPLY_SETTING').strip().upper() or 'APPLY_SETTING'
    if normalized_mode == 'CLEAN':
        return True
    if normalized_mode == 'KEEP':
        return False
    return bool(getattr(params, 'izom_propui_free_clean_old_targets_on_apply', True))


def _izom_propui_free_owner_key(owner):
    try:
        return int(owner.as_pointer())
    except (AttributeError, TypeError, ValueError):
        return id(owner)


def _izom_propui_free_default_owner_path(params):
    return str(getattr(params, 'izom_propui_free_default_target_owner_path', '') or '').strip()


def _izom_propui_free_entry_owner_path(params, entry):
    return _izom_propui_free_default_owner_path(params)


def _izom_propui_free_resolve_owner_path_cached(owner_path, owner_by_path=None):
    path = str(owner_path or '').strip()
    if owner_by_path is None:
        return izom_propui_free_resolve_owner_path(path)
    if path not in owner_by_path:
        owner_by_path[path] = izom_propui_free_resolve_owner_path(path)
    return owner_by_path.get(path)


def _izom_propui_free_resolve_entry_owner(params, entry, owner_by_path=None):
    return _izom_propui_free_resolve_owner_path_cached(
        _izom_propui_free_entry_owner_path(params, entry),
        owner_by_path,
    )


def _izom_propui_free_resolved_target_owners(
        params,
        entries=None,
        *,
        include_default=True,
        owner_by_path=None,
):
    owners = []
    seen = set()
    paths = []
    if include_default:
        paths.append(_izom_propui_free_default_owner_path(params))
    for path in paths:
        owner = _izom_propui_free_resolve_owner_path_cached(path, owner_by_path)
        if owner is None:
            continue
        key = _izom_propui_free_owner_key(owner)
        if key in seen:
            continue
        seen.add(key)
        owners.append((path, owner))
    return owners


def _izom_propui_free_resolved_cleanup_target_owners(params, current_owner_items, *, owner_by_path=None):
    owners = []
    missing_paths = []
    seen = set()
    for owner_path, owner in current_owner_items or ():
        if owner is None:
            continue
        owner_key = _izom_propui_free_owner_key(owner)
        if owner_key in seen:
            continue
        seen.add(owner_key)
        owners.append((str(owner_path or '').strip(), owner))
    for owner_path in _izom_propui_free_last_synced_owner_paths(params):
        owner = _izom_propui_free_resolve_owner_path_cached(owner_path, owner_by_path)
        if owner is None:
            missing_paths.append(owner_path)
            continue
        owner_key = _izom_propui_free_owner_key(owner)
        if owner_key in seen:
            continue
        seen.add(owner_key)
        owners.append((owner_path, owner))
    return owners, missing_paths


def _izom_propui_free_entries_for_sync_mode(_context, params, _sync_mode='ALL_MANAGED', *, snapshots=None):
    if snapshots is None:
        return izom_propui_free_runtime_entries(params)
    return _izom_propui_free_runtime_entries_from_snapshot_state(
        snapshots,
        _izom_propui_free_build_state_from_snapshots(snapshots),
    )


def _izom_propui_free_owner_custom_prop_ids(owner):
    if owner is None:
        return set()
    try:
        return {
            str(key)
            for key in owner.keys()
            if not _izom_propui_free_should_skip_import_key(key)
        }
    except IZOM_PROPUI_FREE_RECOVERABLE_ERRORS as exc:
        izom_propui_free_log_recovered(
            category='UI',
            exception=exc,
        )
        return set()


def _izom_propui_free_managed_prop_ids_by_owner_path(params, entries):
    result = {}
    for entry in entries or []:
        if not _izom_propui_free_syncable_prop_type(entry.get('prop_type')):
            continue
        prop_id = str(entry.get('prop_id', '') or '').strip()
        owner_path = _izom_propui_free_entry_owner_path(params, entry)
        if prop_id and owner_path:
            result.setdefault(owner_path, set()).add(prop_id)
    return result


def _izom_propui_free_managed_prop_ids_from_entries(entries):
    return {
        prop_id
        for entry in entries or []
        if _izom_propui_free_syncable_prop_type(entry.get('prop_type'))
        for prop_id in (str(entry.get('prop_id', '') or '').strip(),)
        if prop_id
    }


def _izom_propui_free_current_prop_owner_maps(params, entries, *, owner_by_path=None):
    ids_by_owner_path = {}
    owner_keys_by_prop_id = {}
    for entry in entries or []:
        if not _izom_propui_free_syncable_prop_type(entry.get('prop_type')):
            continue
        prop_id = str(entry.get('prop_id', '') or '').strip()
        owner_path = _izom_propui_free_entry_owner_path(params, entry)
        if not prop_id or not owner_path:
            continue
        owner = _izom_propui_free_resolve_owner_path_cached(owner_path, owner_by_path)
        if owner is None:
            continue
        ids_by_owner_path.setdefault(owner_path, set()).add(prop_id)
        owner_keys_by_prop_id.setdefault(prop_id, set()).add(_izom_propui_free_owner_key(owner))
    return ids_by_owner_path, owner_keys_by_prop_id


def _izom_propui_free_native_conflicts_by_owner_path(params, entries, *, owner_by_path=None):
    # A conflict is any Property ID the editor wants to write that already
    # exists on the target, regardless of whether PropUI generated it on a
    # previous Apply or it was hand-made the native Blender way. The
    # native-vs-generated distinction only changes how OVERWRITE resolves the
    # value (see execute()), not whether the collision is surfaced.
    conflicts = {}
    for owner_path, managed_ids in _izom_propui_free_managed_prop_ids_by_owner_path(params, entries).items():
        owner = _izom_propui_free_resolve_owner_path_cached(owner_path, owner_by_path)
        if owner is None:
            continue
        matching_ids = _izom_propui_free_owner_custom_prop_ids(owner) & managed_ids
        if matching_ids:
            conflicts[owner_path] = matching_ids
    return conflicts


def _izom_propui_free_native_conflict_summary(conflicts):
    labels = []
    for owner_path, prop_ids in sorted((conflicts or {}).items()):
        label = izom_propui_free_owner_path_label(owner_path)
        ids = ", ".join(sorted(prop_ids))
        labels.append(f"{label}: {ids}")
    return " | ".join(labels)


def _izom_propui_free_native_conflict_prop_keys(conflicts, *, owner_by_path=None):
    result = set()
    for owner_path, prop_ids in (conflicts or {}).items():
        owner = _izom_propui_free_resolve_owner_path_cached(owner_path, owner_by_path)
        if owner is None:
            continue
        owner_key = _izom_propui_free_owner_key(owner)
        result.update((owner_key, prop_id) for prop_id in prop_ids)
    return result


def _izom_propui_free_notify_idprop_owners_changed(owners):
    # Writing/removing idprops from Python fires no notifier, so generated
    # panels and drivers reading the values do not refresh until the depsgraph
    # is poked. Tag each touched owner for a depsgraph update and request a
    # redraw so the change shows immediately instead of after a mouse-move.
    seen = set()
    for owner in owners or ():
        if owner is None:
            continue
        owner_key = _izom_propui_free_owner_key(owner)
        if owner_key in seen:
            continue
        seen.add(owner_key)
        try:
            (getattr(owner, 'id_data', None) or owner).update_tag()
        except (AttributeError, ReferenceError, RuntimeError, TypeError, ValueError) as exc:
            izom_propui_free_log_recovered(
                category='UI',
                exception=exc,
            )
    if seen:
        _izom_propui_free_tag_all_redraw()


