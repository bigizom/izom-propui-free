def _izom_propui_free_clear_runtime_session_caches():
    global _IZOM_PROPUI_FREE_VALUE_LABEL_UPDATE_CALLBACK_SUSPEND_DEPTH
    global _IZOM_PROPUI_FREE_ENTRY_RUNTIME_UPDATE_CALLBACK_SUSPEND_DEPTH

    from . import helper_cache_updates_float_storage as _float_storage
    from .lifecycle import izom_propui_free_unregister_lifecycle_timer

    for timer_name, timer_fn, label in (
        (
            _float_storage._IZOM_PROPUI_FREE_FLOAT_STORAGE_TIMER_NAME,
            _float_storage._izom_propui_free_flush_deferred_float_array_storage_commits,
            "float-array storage commit",
        ),
    ):
        try:
            izom_propui_free_unregister_lifecycle_timer(timer_name, timer_fn)
        except IZOM_PROPUI_FREE_RECOVERABLE_ERRORS as exc:
            izom_propui_free_log_recovered(
                f"Could not unregister deferred PropUI {label} timer",
                category='UI',
                exception=exc,
            )

    _float_storage._IZOM_PROPUI_FREE_DEFERRED_FLOAT_ARRAY_STORAGE_TIMER_ACTIVE = False
    _IZOM_PROPUI_FREE_PROP_ID_UPDATE_GUARD.clear()
    _IZOM_PROPUI_FREE_DISPLAY_ORDER_UPDATE_GUARD.clear()
    _IZOM_PROPUI_FREE_RANGE_UPDATE_GUARD.clear()
    _IZOM_PROPUI_FREE_VALUE_LABEL_UPDATE_GUARD.clear()
    _IZOM_PROPUI_FREE_EDITOR_FLOAT_UPDATE_GUARD.clear()
    _IZOM_PROPUI_FREE_EDITOR_SETTINGS_UPDATE_GUARD.clear()
    _IZOM_PROPUI_FREE_ACTIVE_INDEX_UPDATE_GUARD.clear()
    _IZOM_PROPUI_FREE_LIST_CONTEXT_UPDATE_GUARD.clear()
    _IZOM_PROPUI_FREE_BULK_ENTRY_UPDATE_GUARD.clear()
    _IZOM_PROPUI_FREE_VISIBILITY_DEPTH_UPDATE_GUARD.clear()
    _IZOM_PROPUI_FREE_VISIBILITY_MATCH_UPDATE_GUARD.clear()
    _IZOM_PROPUI_FREE_AVAILABILITY_DEPTH_UPDATE_GUARD.clear()
    _IZOM_PROPUI_FREE_AVAILABILITY_MATCH_UPDATE_GUARD.clear()
    _IZOM_PROPUI_FREE_NORMALIZE_DEPENDENT_GUARD.clear()
    _IZOM_PROPUI_FREE_ARRAY_SHAPE_UPDATE_GUARD.clear()
    _IZOM_PROPUI_FREE_ENTRY_TYPE_UPDATE_GUARD.clear()
    _IZOM_PROPUI_FREE_ENTRY_PARAMS_CACHE.clear()
    _IZOM_PROPUI_FREE_ENTRY_PARAMS_CACHE_STATE.clear()
    _IZOM_PROPUI_FREE_ENTRY_PARAMS_CACHE_OWNER_STATE.clear()
    _IZOM_PROPUI_FREE_TEXT_BLOCK_UPDATE_GUARD.clear()
    _IZOM_PROPUI_FREE_DEFERRED_FLOAT_ARRAY_STORAGE_COMMITS.clear()
    _IZOM_PROPUI_FREE_CHILD_COMPARE_INFO_CACHE.clear()
    _IZOM_PROPUI_FREE_VALUE_LABEL_UPDATE_CALLBACK_SUSPEND_DEPTH = 0
    _IZOM_PROPUI_FREE_ENTRY_RUNTIME_UPDATE_CALLBACK_SUSPEND_DEPTH = 0
    izom_propui_free_clear_value_access_memo()


def _izom_propui_free_value_label_update_callbacks_suspended():
    return _IZOM_PROPUI_FREE_VALUE_LABEL_UPDATE_CALLBACK_SUSPEND_DEPTH > 0


def _izom_propui_free_suspend_value_label_update_callbacks():
    global _IZOM_PROPUI_FREE_VALUE_LABEL_UPDATE_CALLBACK_SUSPEND_DEPTH
    _IZOM_PROPUI_FREE_VALUE_LABEL_UPDATE_CALLBACK_SUSPEND_DEPTH += 1
    return _IZOM_PROPUI_FREE_VALUE_LABEL_UPDATE_CALLBACK_SUSPEND_DEPTH


